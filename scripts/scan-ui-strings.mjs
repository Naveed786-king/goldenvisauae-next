// Collects every translatable UI text used with t('...') or <T>...</T>
// and writes src/lib/i18n/ui-strings.ts.  Run: npm run i18n:scan
import fs from 'fs';
import path from 'path';

const root = path.resolve('src');
const files = [];
(function walk(d) {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name);
    if (e.isDirectory()) walk(p);
    else if (/\.(tsx?|mjs)$/.test(e.name) && !p.includes(`${path.sep}admin`) ) files.push(p);
  }
})(root);

const set = new Set();
for (const f of files) {
  const s = fs.readFileSync(f, 'utf8');
  for (const m of s.matchAll(/\bt\('((?:[^'\\]|\\.)+)'\)/g)) set.add(m[1].replace(/\\'/g, "'"));
  for (const m of s.matchAll(/<T>([^<{}]+)<\/T>/g)) set.add(m[1].trim());
}

// Texts that are passed as variables
const extra = JSON.parse(fs.readFileSync(path.resolve('scripts/ui-extra.json'), 'utf8'));
extra.forEach((x) => set.add(x));
set.delete('');

const list = [...set].sort((a, b) => a.localeCompare(b));
const out = `// AUTO-GENERATED by scripts/scan-ui-strings.mjs — do not edit by hand.\n// English UI texts that are translated automatically into every language.\nexport const UI_STRINGS: string[] = ${JSON.stringify(list, null, 2)};\n`;
fs.writeFileSync(path.resolve('src/lib/i18n/ui-strings.ts'), out);
console.log(`ui-strings: ${list.length} texts`);
